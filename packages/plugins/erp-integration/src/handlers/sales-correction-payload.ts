import type {
    ErpHeaderFields,
    ErpLineRow,
    SalesCorrectionErp,
    SalesCorrectionGoodsLineErp,
    SalesCorrectionServiceLineErp,
} from '@mivend/plugin-erp-order';

import {
    bool,
    discountCondition,
    discounts,
    flt,
    fltZero,
    int,
    lineNumber,
    money,
    moneyZero,
    records,
    ref,
    str,
    time,
    vat,
} from './erp-document-payload';
import type { Payload } from './erp-document-payload';

export function salesCorrectionFields(p: Payload): ErpHeaderFields<SalesCorrectionErp> {
    return {
        number: str(p.number) ?? '',
        date: time(p.date),
        operationKind: ref(p.operationKind),
        correctedDocument: ref(p.correctedDocument),
        basisDocument: ref(p.basisDocument),
        orderId: str(p.orderId),
        counterpartyId: str(p.counterpartyId),
        contractId: str(p.contractId),
        organizationId: str(p.organizationId),
        departmentId: str(p.departmentId),
        warehouseId: str(p.warehouseId),
        responsibleId: str(p.responsibleId),
        project: ref(p.project),
        currency: str(p.currency),
        exchangeRate: flt(p.exchangeRate),
        exchangeMultiplicity: flt(p.exchangeMultiplicity),
        totalAmountMinor: moneyZero(p.totalAmount),
        vatAccounted: bool(p.vatAccounted),
        amountIncludesVat: bool(p.amountIncludesVat),
        correctVat: bool(p.correctVat),
        correctAccountingAndTax: bool(p.correctAccountingAndTax),
        priceTypeId: str(p.priceTypeId),
        salesCondition: ref(p.salesCondition),
        discountCard: ref(p.discountCard),
        deliveryAddress: str(p.deliveryAddress),
        deliveryAddressAddition: str(p.deliveryAddressAddition),
        consignorId: str(p.consignorId),
        consigneeId: str(p.consigneeId),
        bankAccountId: str(p.bankAccountId),
        transferKind: ref(p.transferKind),
        comment: str(p.comment),
        accounting: ref(p.accounting),
        setComponents: records(p.setComponents),
        serialNumbers: records(p.serialNumbers),
        setSerialNumbers: records(p.setSerialNumbers),
        packageBarcodes: records(p.packageBarcodes),
        traceability: records(p.traceability),
    };
}

const beforeValues = (l: Payload) => ({
    quantityBeforeCorrection: flt(l.quantityBeforeCorrection),
    priceBeforeCorrectionMinor: money(l.priceBeforeCorrection),
    amountBeforeCorrectionMinor: money(l.amountBeforeCorrection),
    vatAmountBeforeCorrectionMinor: money(l.vatAmountBeforeCorrection),
    quantityBeforeChange: flt(l.quantityBeforeChange),
    priceBeforeChangeMinor: money(l.priceBeforeChange),
    amountBeforeChangeMinor: money(l.amountBeforeChange),
    vatAmountBeforeChangeMinor: money(l.vatAmountBeforeChange),
    vatCodeBeforeChange: str(l.vatCodeBeforeChange),
});

export function salesCorrectionGoodsLines(p: Payload): ErpLineRow<SalesCorrectionGoodsLineErp>[] {
    return records(p.goods).map(l => ({
        lineNumber: lineNumber(l),
        lineId: str(l.lineId),
        productId: str(l.productId),
        characteristicId: str(l.characteristicId),
        seriesId: str(l.seriesId),
        unitId: str(l.unitId),
        unitCoefficient: fltZero(l.unitCoefficient),
        quantity: fltZero(l.quantity),
        priceMinor: moneyZero(l.price),
        amountMinor: moneyZero(l.amount),
        ...vat(l),
        ...beforeValues(l),
        ...discounts(l),
        ...discountCondition(l),
        orderId: str(l.orderId),
        warehouseId: str(l.warehouseId),
        quality: ref(l.quality),
        writeOffMethod: ref(l.writeOffMethod),
        inSaleDocument: bool(l.inSaleDocument),
        reflectInStock: bool(l.reflectInStock),
        traceable: bool(l.traceable),
        belongsTo: str(l.belongsTo),
        originCountry: ref(l.originCountry),
        customsCode: ref(l.customsCode),
        customsCodeBeforeChange: ref(l.customsCodeBeforeChange),
        placesUnitId: str(l.placesUnitId),
        placesQuantity: flt(l.placesQuantity),
        linkKey: int(l.linkKey),
        rowKey: int(l.rowKey),
        shippedDelta: fltZero(l.shippedDelta),
    }));
}

export function salesCorrectionServiceLines(
    p: Payload,
): ErpLineRow<SalesCorrectionServiceLineErp>[] {
    return records(p.services).map(l => ({
        lineNumber: lineNumber(l),
        productId: str(l.productId),
        content: str(l.content),
        contentBeforeChange: str(l.contentBeforeChange),
        quantity: fltZero(l.quantity),
        priceMinor: moneyZero(l.price),
        amountMinor: moneyZero(l.amount),
        ...vat(l),
        ...beforeValues(l),
        ...discounts(l),
        ...discountCondition(l),
        orderId: str(l.orderId),
        inSaleDocument: bool(l.inSaleDocument),
        reflectInStock: bool(l.reflectInStock),
    }));
}
