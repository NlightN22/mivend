import type {
    CustomerClaimErp,
    CustomerClaimGoodsLineErp,
    CustomerClaimServiceLineErp,
    ErpHeaderFields,
    ErpLineRow,
} from '@mivend/plugin-erp-order';

import {
    bool,
    discounts,
    flt,
    fltZero,
    int,
    lineNumber,
    money,
    moneyZero,
    records,
    ref,
    str,
    time,
    vat,
} from './erp-document-payload';
import type { Payload } from './erp-document-payload';

export function customerClaimFields(p: Payload): ErpHeaderFields<CustomerClaimErp> {
    return {
        number: str(p.number) ?? '',
        date: time(p.date),
        organizationId: str(p.organizationId),
        counterpartyId: str(p.counterpartyId),
        contractId: str(p.contractId),
        departmentId: str(p.departmentId),
        responsibleId: str(p.responsibleId),
        projectId: str(p.projectId),
        warehouseId: str(p.warehouseId),
        orderId: str(p.orderId),
        basisDocument: ref(p.basisDocument),
        currency: str(p.currency),
        exchangeRate: flt(p.exchangeRate),
        exchangeMultiplicity: flt(p.exchangeMultiplicity),
        priceTypeId: str(p.priceTypeId),
        salesConditionId: str(p.salesConditionId),
        discountCardId: str(p.discountCardId),
        vatAccounted: bool(p.vatAccounted),
        amountIncludesVat: bool(p.amountIncludesVat),
        totalAmountMinor: moneyZero(p.totalAmount),
        totalWeight: flt(p.totalWeight),
        comment: str(p.comment),
        status: ref(p.status),
        hasClaim: bool(p.hasClaim),
        workedOut: bool(p.workedOut),
        receiptKind: ref(p.receiptKind),
        saleWasChanged: bool(p.saleWasChanged),
        saleDocumentsUpdatePending: bool(p.saleDocumentsUpdatePending),
        transferDocument: ref(p.transferDocument),
        goodsTransferDocument: ref(p.goodsTransferDocument),
        supplierClaimDocument: ref(p.supplierClaimDocument),
        internalMovementDocument: ref(p.internalMovementDocument),
    };
}

export function customerClaimGoodsLines(p: Payload): ErpLineRow<CustomerClaimGoodsLineErp>[] {
    return records(p.goods).map(l => ({
        lineNumber: lineNumber(l),
        linkKey: int(l.linkKey),
        rowKey: int(l.rowKey),
        productId: str(l.productId),
        characteristicId: str(l.characteristicId),
        seriesId: str(l.seriesId),
        unitId: str(l.unitId),
        unitCoefficient: flt(l.unitCoefficient),
        placesUnitId: str(l.placesUnitId),
        places: flt(l.places),
        quantity: fltZero(l.quantity),
        priceMinor: moneyZero(l.price),
        amountMinor: moneyZero(l.amount),
        ...vat(l),
        weight: flt(l.weight),
        quality: ref(l.quality),
        warehouseId: str(l.warehouseId),
        returnDocument: ref(l.returnDocument),
        hasClaim: bool(l.hasClaim),
        returnReason: ref(l.returnReason),
        decision: ref(l.decision),
        comment: str(l.comment),
        inventoryDocumentId: str(l.inventoryDocumentId),
        ...discounts(l),
        orderId: str(l.orderId),
        saleDocumentId: str(l.saleDocumentId),
        receiptOrderId: str(l.receiptOrderId),
        costMinor: money(l.cost),
        batchDocument: ref(l.batchDocument),
        lineStatus: str(l.lineStatus),
        transferredTo: ref(l.transferredTo),
        refusalReason: str(l.refusalReason),
    }));
}

export function customerClaimServiceLines(p: Payload): ErpLineRow<CustomerClaimServiceLineErp>[] {
    return records(p.services).map(l => ({
        lineNumber: lineNumber(l),
        productId: str(l.productId),
        content: str(l.content),
        quantity: fltZero(l.quantity),
        priceMinor: moneyZero(l.price),
        amountMinor: moneyZero(l.amount),
        ...vat(l),
        ...discounts(l),
        orderId: str(l.orderId),
        returnReason: ref(l.returnReason),
        comment: str(l.comment),
        decision: ref(l.decision),
        hasClaim: bool(l.hasClaim),
        saleDocumentId: str(l.saleDocumentId),
    }));
}
